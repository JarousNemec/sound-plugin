package cz.jarda.soundplugin.soundgen

import java.io.ByteArrayInputStream
import java.io.File
import javax.sound.midi.MidiSystem
import javax.sound.sampled.AudioFileFormat
import javax.sound.sampled.AudioFormat
import javax.sound.sampled.AudioInputStream
import javax.sound.sampled.AudioSystem
import kotlin.math.abs
import kotlin.math.log10

/**
 * Regenerates the bundled `demo-midi` soundpack from [DemoSoundCatalog]:
 *  - `<packDir>/sounds/<name>.wav` (rendered audio shipped with the plugin),
 *  - `<midiDir>/<name>.mid` (editable sources, not shipped),
 *  - `<packDir>/soundpack.json` (manifest built from the same catalog).
 *
 * Run via `./gradlew generateDemoSounds` (optionally `-Psoundfont=<file.sf2>`).
 * Usage: `GenerateDemoPack <packDir> <midiDir> [--soundfont <file.sf2>]`
 */
fun main(args: Array<String>) {
    require(args.size >= 2) { "usage: GenerateDemoPack <packDir> <midiDir> [--soundfont <file.sf2>]" }
    val packDir = File(args[0])
    val midiDir = File(args[1])
    val soundfont = args.indexOf("--soundfont").takeIf { it >= 0 }?.let { File(args[it + 1]) }

    val soundbank = soundfont?.let {
        println("Using soundfont ${it.absolutePath}")
        MidiSystem.getSoundbank(it)
    }
    val renderer = MidiRenderer(soundbank)

    val programs = DemoSoundCatalog.ALL.flatMap { d -> d.notes.map { it.program } }.distinct().sorted()
    for (p in programs) println("program %3d -> %s".format(p, renderer.instrumentName(p)))

    val soundsDir = File(packDir, "sounds")
    soundsDir.mkdirs()
    // Drop stale outputs so renamed/removed sounds do not linger.
    soundsDir.listFiles { f -> f.extension == "wav" }?.forEach { it.delete() }
    midiDir.listFiles { f -> f.extension == "mid" }?.forEach { it.delete() }

    val names = DemoSoundCatalog.ALL.map { it.name }
    require(names.size == names.toSet().size) { "duplicate sound names in catalog" }

    for (def in DemoSoundCatalog.ALL) {
        renderer.writeMidi(def, File(midiDir, "${def.name}.mid"))
        val pcm = renderer.render(def)
        writeWav(pcm, File(soundsDir, "${def.name}.wav"))
        val peak = pcm.maxOf { abs(it.toInt()) } / Short.MAX_VALUE.toDouble()
        println("%-26s %-34s %4d ms  peak %5.1f dBFS  vol %3d".format(
            def.name, def.eventId, pcm.size * 1000 / MidiRenderer.SAMPLE_RATE, 20 * log10(peak), def.volume))
    }

    File(packDir, "soundpack.json").writeText(manifestJson(), Charsets.UTF_8)
    println("Generated ${DemoSoundCatalog.ALL.size} sounds into ${packDir.absolutePath}")
}

private fun writeWav(pcm: ShortArray, target: File) {
    val bytes = ByteArray(pcm.size * 2)
    for (i in pcm.indices) {
        val s = pcm[i].toInt()
        bytes[i * 2] = (s and 0xFF).toByte()
        bytes[i * 2 + 1] = ((s shr 8) and 0xFF).toByte()
    }
    val format = AudioFormat(MidiRenderer.SAMPLE_RATE.toFloat(), 16, 1, true, false)
    AudioInputStream(ByteArrayInputStream(bytes), format, pcm.size.toLong()).use {
        AudioSystem.write(it, AudioFileFormat.Type.WAVE, target)
    }
}

/** Bump when the sounds or mappings change, so existing installs get refreshed on startup. */
private const val PACK_VERSION = "1.1.0"

private fun json(s: String): String = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""

private fun manifestJson(): String {
    val mappings = DemoSoundCatalog.ALL.joinToString(",\n") { d ->
        "    { \"eventId\": ${json(d.eventId)}, \"soundFile\": ${json("sounds/${d.name}.wav")}, \"volume\": ${d.volume} }"
    }
    return """
        |{
        |  "schemaVersion": 1,
        |  "id": "demo-midi",
        |  "name": "Demo (MIDI)",
        |  "author": "SoundPlugin",
        |  "description": "Demo pack with a short MIDI-style cue for every lifecycle event and a curated set of IDE actions. Generated by ./gradlew generateDemoSounds - do not edit by hand.",
        |  "version": ${json(PACK_VERSION)},
        |  "defaultMappings": [
        |$mappings
        |  ]
        |}
        |""".trimMargin()
}
